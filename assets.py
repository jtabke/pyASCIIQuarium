"""ASCII art assets for asciiquarium.

All visible artwork lives here so the engine code (entity, animation,
rendering, callbacks) in asciiquarium.py stays focused on behavior.

Conventions:
- Every shape is a triple-quoted raw string. The leading newline is
  significant; Entity._update_dimensions strips outer newlines and
  splits on '\\n'.
- Mask digits 1-9 are random-color placeholders (1=body, 2=dorsal,
  3=flippers, 4=eye→W, 5=mouth, 6=tail, 7=gills); single letters
  (uppercase=bold) map directly via COLOR_CHAR_MAP.
- '?' in a shape marks transparent cells (Perl Term::Animation default).
"""

